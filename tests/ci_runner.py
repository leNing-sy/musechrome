"""Run an isolated fixture suite and expose failures in GitHub check annotations."""

from __future__ import annotations

import subprocess
import sys
import uuid
from pathlib import Path


SUITES = {
    "test_store.py", "test_auto_login.py", "test_mail_assist_ui.py",
    "test_browser_parity.py", "test_app_pruning.py", "test_update.py",
}


def annotation_text(text: str) -> str:
    return text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


def main() -> int:
    if len(sys.argv) != 2 or sys.argv[1] not in SUITES:
        print("Usage: python tests/ci_runner.py <supported test filename>", file=sys.stderr)
        return 2
    name = sys.argv[1]
    path = Path(__file__).resolve().parent / name
    try:
        result = subprocess.run(
            [sys.executable, str(path), "-v"],
            cwd=path.parent.parent,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            encoding="utf-8",
            errors="replace",
            timeout=180,
        )
        output, status = result.stdout, result.returncode
    except subprocess.TimeoutExpired as exc:
        output = exc.stdout or b""
        if isinstance(output, bytes):
            output = output.decode("utf-8", errors="replace")
        output += "\nTest suite exceeded the 180 second limit.\n"
        status = 124

    # Fixture output is data, never a workflow command. The annotation below is
    # generated by this wrapper and escapes newlines and command escape bytes.
    marker = uuid.uuid4().hex
    print(f"::stop-commands::{marker}")
    print(output, end="" if output.endswith("\n") else "\n")
    print(f"::{marker}::")
    if status:
        detail = annotation_text(output[-24000:] or f"Process exited with status {status}.")
        print(f"::error file=tests/{name},title=Test failure::{detail}")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
